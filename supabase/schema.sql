-- Run this once in Supabase: SQL Editor -> New query -> paste -> Run.
-- Access is restricted with row-level security. The application's service-role key bypasses it.

create table if not exists public.markets (
    id text primary key,
    provider text not null,
    external_id text not null,
    question text not null,
    market_type text not null,
    status text not null,
    yes_outcome_id text,
    opens_at timestamptz,
    closes_at timestamptz,
    topics jsonb not null default '[]'::jsonb,
    raw_payload jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (provider, external_id)
);

create table if not exists public.forecast_snapshots (
    id bigint generated by default as identity primary key,
    market_id text not null references public.markets(id) on delete cascade,
    observed_at timestamptz not null,
    probability_yes numeric(8, 6) not null check (probability_yes between 0 and 1),
    volume numeric(24, 6),
    open_interest numeric(24, 6),
    liquidity numeric(24, 6),
    recorded_at timestamptz not null default now(),
    unique (market_id, observed_at)
);

create index if not exists ix_forecast_snapshots_market_observed_at
    on public.forecast_snapshots (market_id, observed_at);

create table if not exists public.resolutions (
    market_id text primary key references public.markets(id) on delete cascade,
    outcome text not null,
    resolved_at timestamptz not null,
    source text not null,
    is_verified boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.markets enable row level security;
alter table public.forecast_snapshots enable row level security;
alter table public.resolutions enable row level security;

grant select, insert, update on public.markets to service_role;
grant select, insert, update on public.forecast_snapshots to service_role;
grant select, insert, update on public.resolutions to service_role;
grant usage, select on all sequences in schema public to service_role;
